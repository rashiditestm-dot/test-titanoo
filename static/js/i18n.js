  let lang = 'fa';
  try {
    const saved = localStorage.getItem('titan_lang') || localStorage.getItem('titan-language');
    if (saved === 'en') lang = 'en';
  } catch (_) {}

  function t(key, vars) {
    if (vars && Number(vars.n) === 1 && messages[key + '_one']) key += '_one';
    const pair = messages[key];
    let text = pair ? pair[lang === 'en' ? 1 : 0] : key;
    if (vars) Object.entries(vars).forEach(([name, value]) => {
      text = text.split('{' + name + '}').join(String(value));
    });
    return text;
  }

  const messageKeys = new Map();
  Object.entries(messages).forEach(([key, pair]) => {
    pair.forEach(text => { if (text && !messageKeys.has(text)) messageKeys.set(text, key); });
  });
  function keyFor(text) { return messageKeys.get(text) || ''; }

  function apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(el => {
      let vars;
      const raw = el.getAttribute('data-i18n-vars');
      if (raw) {
        try { vars = JSON.parse(raw); } catch (_) { vars = { n: raw }; }
        if (typeof vars !== 'object') vars = { n: vars };
      }
      el.textContent = t(el.getAttribute('data-i18n'), vars);
    });
    const attributes = { ph: 'placeholder', aria: 'aria-label', title: 'title', alt: 'alt' };
    Object.entries(attributes).forEach(([suffix, attr]) => {
      root.querySelectorAll('[data-i18n-' + suffix + ']').forEach(el => {
        el.setAttribute(attr, t(el.getAttribute('data-i18n-' + suffix)));
      });
    });
    root.querySelectorAll('[data-i18n-tip]').forEach(el => {
      const text = t(el.getAttribute('data-i18n-tip'));
      el.setAttribute('data-tip', text);
      el.setAttribute('aria-label', text);
      if (el.hasAttribute('title')) el.setAttribute('title', text);
    });
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  }

  function setLang(value) {
    lang = value === 'en' ? 'en' : 'fa';
    try { localStorage.setItem('titan_lang', lang); } catch (_) {}
    apply();
    document.dispatchEvent(new Event('titan:lang'));
  }

  apply();
  return { t, keyFor, apply, setLang, get lang() { return lang; }, get locale() { return lang === 'fa' ? 'fa-IR' : 'en-GB'; } };
